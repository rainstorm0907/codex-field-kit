#!/usr/bin/env node
// Generate Codex native role files from the agent-taskforce contracts in skills/.
// Usage: node scripts/build-roles.mjs [--check]
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const body = (text) => text.replace(/^---\r?\n[\s\S]*?\r?\n---\r?\n/, '').trim();
const read = async (rel) => body(await readFile(path.join(root, 'skills', rel), 'utf8'));

const receiving = await read('dispatched/SKILL.md');
const teammate = await read('agent-taskforce/TEAMMATE.md');
const runtime = `# Codex runtime

Your role is assigned; inherited lead conversation does not make you the lead. The brief and authoritative artifacts define your task. Do not invent a mission or frame when none is needed. The receiving contract is included below.

Codex owns native agents, messaging, follow-ups, waiting and results. The installed agent-taskforce skill's \`runtimes/codex.md\` maps the native tools; resolve its links from that skill directory. Read the dispatching skill before delegating. Preserve the approved team roster.

Roles are not pinned to a model. For new subagents, choose a model and effort the native spawn tool offers, according to the model-guide skill and the user's constraints. A subagent is a session that remembers: send the next related slice to the same subagent with followup_task, and start a new one only for a different problem, a cold review, or one stuck on a wrong idea. Do not change your own assigned model or claim a runtime-confirmed model from a requested label.`;
const helper = '# Subagent\n\nYou are a subagent of the session that sent this brief — the lead or a teammate. You are not on the team roster. Execute the bounded task in your brief. Verify local facts and return evidence to the sender. Implement only when authorized. You do not own the wider workstream or its integration. If it cannot be completed within your boundary or budget, return the covered surface, exact blocker and recommended next cut.';

const roles = [
  ['taskforce_owner', 'Continuing owner of a bounded outcome through investigation, authorized implementation and local verification.',
    [teammate, await read('agent-taskforce/teammate/workstream-owner.md')]],
  ['taskforce_verifier', 'Independent verifier of artifacts and acceptance evidence in a fresh context.',
    [teammate, await read('agent-taskforce/teammate/independent-verifier.md')]],
  ['taskforce_klong', '클롱이: a continuing companion reviewer attached to a session; verifier contract plus the companion role.',
    [teammate, await read('agent-taskforce/teammate/independent-verifier.md'), await read('agent-taskforce/teammate/klong.md')]],
  ['taskforce_helper', 'Subagent of the lead or a teammate for a focused map, check or settled subtask; returns evidence without taking the wider outcome.',
    [helper]],
];

await mkdir(path.join(root, 'agents'), { recursive: true });
for (const [name, description, parts] of roles) {
  const instructions = [`# Taskforce role: ${name}`, runtime, ...parts, receiving].join('\n\n');
  const digest = createHash('sha256').update(instructions).digest('hex');
  // Role files leave model and effort out so the lead picks them per task.
  const content = `# Generated by scripts/build-roles.mjs from skills/. Edit the skill sources instead.\n# Source SHA256: ${digest}\nname = ${JSON.stringify(name)}\ndescription = ${JSON.stringify(description)}\ndeveloper_instructions = ${JSON.stringify(instructions)}\n`;
  const dest = path.join(root, 'agents', `${name}.toml`);
  if (check) {
    if ((await readFile(dest, 'utf8')) !== content) throw new Error(`Stale generated role: ${name}`);
  } else {
    await writeFile(dest, content);
  }
  console.log(`${name}: ${check ? 'current' : 'generated'}`);
}
